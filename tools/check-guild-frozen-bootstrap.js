"use strict";
const assert = require("node:assert/strict");
const guild = require("../modules/guild");
const cooperative = require("../modules/guild/cooperative");
const { setMiscItemBalance } = require("../modules/inventory");
const { readGameplayTableRecords } = require("../modules/gameplay-jsons");
const fixture = require("./fixtures/guild-frozen-empty-interval.json");
const data = cooperative.catalog();
const original = { seasons:data.seasons, intervals:data.intervals, schedules:data.schedules, arenas:data.arenas, bosses:data.bosses };
const owner = {userUid:"1",friendCode:"101",nickname:"FrozenOwner",level:20,inventory:{}};
setMiscItemBalance(owner,101,1500);
const clock=new Date("2025-04-10T10:54:58Z");
const ctx={userDb:{users:{1:owner}},getServerNowDate:()=>clock,getEffectiveContentsTags:()=>fixture.tags};
guild.handleRequest(ctx,owner,3400,{guildName:"FrozenGuild",guildJoinType:0,badgeId:"0",greeting:""});
try {
  data.seasons=fixture.seasons;
  data.intervals=fixture.intervalTable.records;
  data.schedules=fixture.schedules;
  data.arenas=fixture.arenas;
  data.bosses=fixture.bosses;
  const chosen=cooperative.selectedSeason(ctx);
  assert.equal(chosen.season.m_SeasonID,110012,"frozen tables choose the latest compatible native-defined season without an unavailable static interval");
  assert.equal(chosen.season.m_DateStrID,"DATE_GUILD_DUNGEON_SEASON_GIGAS_2025_2");
  const intervals=guild.buildGuildSeasonIntervals(ctx,owner);
  assert.equal(intervals.length,1,"frozen guild calendar stays enabled when INTERVAL_TEMPLET is empty");
  assert.equal(intervals[0].strKey,chosen.season.m_DateStrID);
  assert(Number.isInteger(intervals[0].key)&&intervals[0].key>0);
  assert.equal(owner && ctx.userDb.guilds[owner.guildUid].cooperative.startMs,intervals[0].startDate.getTime());
  assert.equal(Object.keys(ctx.userDb.guilds[owner.guildUid].cooperative.sessions).length,0,"login calendar does not eagerly initialize Boss stats or battlefield state");
  const info=guild.handleRequest(ctx,owner,3471,{guildUid:owner.guildUid});
  assert.equal(info.seasonId,110012);
  assert.equal(info.sessionId,1);
  assert.equal(info.bossData.playCount,5);
  assert.equal(info.arenaList.length,4);
  assert(cooperative.catalog().bosses.some(row=>row.m_StageID===info.bossData.stageId));
  assert.equal(guild.cancelGuildBattle(ctx,owner),null,"closing a socket without a reservation cannot need a guild season");
  const stored=ctx.userDb.guilds[owner.guildUid].cooperative;
  const progress=stored.sessions[info.sessionId];
  progress.members[owner.userUid].pending={kind:"arena",token:"synthetic-pending",arenaIndex:progress.arenas[0].arenaIndex};
  progress.arenas[0].playUserUid=owner.userUid;
  data.seasons=[];
  const canceled=guild.cancelGuildBattle(ctx,owner);
  assert.equal(canceled.packets[0].packetId,3486,"a stored reservation is safely canceled even while catalog data is unavailable");
  assert.equal(progress.arenas[0].playUserUid,"0");
  assert.equal(progress.members[owner.userUid].pending,null);
  assert.equal(progress.members[owner.userUid].arenaList.length,0,"cancel cannot consume arena attempts");
  assert.equal(guild.cancelGuildBattle(ctx,owner),null);
  assert.equal(guild.cancelGuildBattle(ctx,{userUid:"2",guildUid:"not-in-db"}),null,"stale imported memberships cannot throw during socket close");
  assert.deepEqual(guild.buildGuildSeasonIntervals(ctx,owner),[],"irrecoverably absent catalogs cannot abort unrelated login data");
  data.seasons=fixture.seasons.map(row=>({SeasonId:row.m_SeasonID,SeasonDungeonGroup:row.m_SeasonDungeonGroup,SeasonRaidGroup:row.m_SeasonRaidGroup,SeasonRewardGroup:row.m_SeasonRewardGroup,SeasonDateStrId:row.m_DateStrID,OpenTag:row.listContentsTagAllow[0].toLowerCase()}));
  data.intervals=[{StrKey:"date_guild_dungeon_season_demoltion_2025_2",Key:8519,StartDate:"2025-03-19T10:00:00.0000000Z",EndDate:new Date("2025-04-07T10:00:00Z")},{strKey:"DATE_GUILD_DUNGEON_SEASON_GIGAS_2025_2",key:8522,startDate:"2025-04-16T10:00:00+00:00",endDate:"2025-05-05T10:00:00Z"}];
  assert.equal(cooperative.selectedSeason(ctx).season.m_SeasonID,100012,"native aliases, case-insensitive tags and explicit UTC offsets preserve latest-started selection");
  assert.equal(guild.buildGuildSeasonIntervals(ctx,owner).length,1);
  assert.equal(guild.handleRequest(ctx,owner,3471,{guildUid:owner.guildUid}).bossData.playCount,5);
  console.log("[guild-frozen-bootstrap] PASS real frozen empty-interval fixture, compatible native map/calendar, lazy login, no-pending/stale close, canceled reservation and date/tag aliases");
} finally {Object.assign(data,original);}
